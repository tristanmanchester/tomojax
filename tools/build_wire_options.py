"""Generate strict wire counterparts of public configuration and correction dataclasses."""

from __future__ import annotations

from dataclasses import MISSING, fields
from pathlib import Path
import sys
from typing import Any, get_args

import tomojax as tj
from tomojax import alignment, corrections, datasets

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "src/tomojax/cli/wire_options.py"


def render() -> str:
    """Keep owner annotations and defaults, substituting the wire forms of arrays and devices."""
    from tomojax._loading_geometry import DeclaredGeometry
    from tomojax.recon.api import MethodConfig
    from tomojax.recon.types import DataTerm, Regularizer

    classes = [
        DeclaredGeometry,
        tj.Grid,
        tj.Detector,
        datasets.SimulationArtefacts,
        alignment.AlignConfig,
        *get_args(MethodConfig.__value__),
        *(
            getattr(corrections, name)
            for name in corrections.__all__
            if isinstance(getattr(corrections, name), type)
            and issubclass(getattr(corrections, name), corrections.Step)
            and name != "Step"
        ),
    ]
    lines = [
        '"""Generated by tools/build_wire_options.py from the owning public dataclasses."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Literal",
        "",
        "from tomojax.wire.arrays import Id, Member, Record, Storage",
    ]
    for cls in classes:
        tagged = cls.__name__.endswith("Config") or issubclass(cls, corrections.Step)
        tag = f', tag="{cls.__name__}"' if tagged else ""
        lines.extend(
            (
                "",
                "",
                f"class {cls.__name__}(Record{tag}):",
                f'    """Wire fields of {cls.__name__}."""',
                "",
            )
        )
        module = vars(sys.modules[cls.__module__])
        for field in fields(cls):
            if not field.init:
                continue
            annotation = str(field.type)
            if field.name == "devices":
                annotation = "tuple[Id, ...] | None"
            elif field.name == "support":
                annotation = "Storage | None"
            elif cls is corrections.Rings and field.name == "geometry":
                annotation = "Member | None"
            else:
                name = annotation.removesuffix(" | None")
                value: Any = module.get(
                    name, {"DataTerm": DataTerm, "Regularizer": Regularizer}.get(name)
                )
                value = getattr(value, "__value__", value)
                if value is not None and get_args(value):
                    resolved = repr(value).removeprefix("typing.").replace("'", '"')
                    annotation = annotation.replace(name, resolved)
            default = field.default
            if field.default_factory is not MISSING:
                default = field.default_factory()
            suffix = "" if default is MISSING else f" = {default!r}"
            lines.append(f"    {field.name}: {annotation}{suffix}".replace("'", '"'))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    _ = TARGET.write_text(render(), encoding="utf-8")
