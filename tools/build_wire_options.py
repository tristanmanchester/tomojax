"""Generate wire configuration types and the installed GUI parameter description."""

from __future__ import annotations

import argparse
from dataclasses import MISSING, fields
import inspect
import json
from pathlib import Path
import re
import sys
from types import ModuleType, NoneType, UnionType
from typing import (
    TYPE_CHECKING,
    Annotated,
    Any,
    Literal,
    TypeAliasType,
    get_args,
    get_origin,
    get_type_hints,
)

import msgspec
from numpydoc.docscrape import NumpyDocString

import tomojax as tj
from tomojax import corrections
from tomojax._parameters import Filter, GeometryName, TiltAbout
from tomojax.cli._parameter_types import option_types

if TYPE_CHECKING:
    from collections.abc import Callable

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "src/tomojax/cli/wire_options.py"
DESCRIPTION = TARGET.with_name("parameters.json")


def wire_annotation(annotation: Any) -> str:
    """Render the resolved type using only the strict wire schema vocabulary."""
    if isinstance(annotation, TypeAliasType):
        # These strings support field-relative errors from the domain constructor.
        return (
            "str"
            if annotation in (Filter, GeometryName, TiltAbout)
            else wire_annotation(annotation.__value__)
        )
    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is tuple:
        return f"tuple[{', '.join(map(wire_annotation, args))}]"
    if origin is UnionType:
        return " | ".join(map(wire_annotation, args))
    if origin is Literal:
        return f"Literal[{', '.join(map(json.dumps, args))}]"
    if annotation is Ellipsis:
        return "..."
    return "None" if annotation is NoneType else annotation.__name__


def render() -> str:
    """Render constructor fields with registered storage and device references at ingress."""
    lines = [
        '"""Generated by tools/build_wire_options.py from the owning public dataclasses."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Literal",
        "",
        "from tomojax.wire.arrays import Id, Member, Record, Storage",
    ]
    for cls in option_types():
        tagged = cls.__name__.endswith("Config") or issubclass(cls, corrections.Step)
        tag = f', tag="{cls.__name__}"' if tagged else ""
        lines.extend(
            (
                "",
                "",
                f"class {cls.__name__}(Record{tag}):",
                f'    """Wire fields of {cls.__name__}."""',
                "",
            )
        )
        hints = get_type_hints(cls)
        for field in fields(cls):
            if not field.init:
                continue
            if field.name == "devices":
                annotation = "tuple[Id, ...] | None"
            elif field.name == "support":
                annotation = "Storage | None"
            elif cls is corrections.Rings and field.name == "geometry":
                annotation = "Member | None"
            else:
                annotation = wire_annotation(hints[field.name])
            default = (
                field.default_factory() if field.default_factory is not MISSING else field.default
            )
            suffix = "" if default is MISSING else f" = {default!r}"
            lines.append(f"    {field.name}: {annotation}{suffix}".replace("'", '"'))
    return "\n".join(lines) + "\n"


def choices(annotation: Any) -> list[Any]:
    """Preserve the owner's ordering, including choices inside nullable and tuple types."""
    if isinstance(annotation, TypeAliasType):
        return choices(annotation.__value__)
    args = get_args(annotation)
    if get_origin(annotation) is Literal:
        return list(args)
    return list(dict.fromkeys(item for part in args for item in choices(part)))


def description() -> dict[str, Any]:
    """Enrich the operation schema with public parameter help, units and domain choices."""
    from tomojax.cli import operations as op

    schema = msgspec.json.schema(op.ExecutionInput)
    definitions = schema["$defs"]
    describe_models(definitions)

    # Distinct Python entry points can share a single protocol command and its wire fields.
    workflows = {
        op.Open: (
            tj.load,
            tj.load_frames,
            tj.load_reconstruction,
            tj.load_alignment,
            tj.load_simulation,
        ),
        op.Inspect: (tj.inspect,),
        op.Correct: (tj.Scan.corrected, tj.Frames.corrected),
        op.Reconstruct: (tj.reconstruct,),
        op.ReconstructSlabs: (tj.reconstruct_slabs,),
        op.Align: (tj.align,),
        op.Simulate: (tj.simulate,),
        op.Project: (tj.project,),
        op.Backproject: (tj.backproject,),
        op.Save: (tj.save,),
        op.Export: (tj.export,),
        op.Select: (tj.Scan.selected, tj.Frames.selected),
        op.Crop: (tj.Scan.cropped, tj.Frames.cropped),
        op.Bin: (tj.Scan.binned,),
        op.Poses: (tj.Scan.with_poses,),
        op.Combine: (tj.Scan.combine,),
        op.RegionPreview: (tj.estimate_region,),
    }
    for operation, owners in workflows.items():
        document = definitions[operation.__name__]
        props = document["properties"]
        public = {}
        for owner in owners:
            by_name = {}
            for name, info in parameters(owner).items():
                wire_name = name
                if (operation, name) in {(op.Reconstruct, "out"), (op.ReconstructSlabs, "info")}:
                    by_name[name] = {"owner": "worker", **info}
                    continue
                if name not in props:
                    wire_name = {
                        "steps": "corrections",
                        "scans": "sources",
                        "scan": "source",
                        "frames": "source",
                        "geometry": "source",
                        "item": "source",
                        "reconstruction": "source",
                    }[name]
                props[wire_name].update(info)
                by_name[name] = wire_name
            public[owner.__qualname__] = by_name
        document["x-python"] = public
    # The open command dispatches to five loaders; save adds overwrite protection.
    definitions["Open"]["properties"]["path"]["description"] = (
        "Acquisition or saved dataset to load. Select its object type with kind."
    )
    definitions["Save"]["properties"]["path"]["description"] = (
        "Output dataset path. Set force to replace existing files."
    )
    inherit_align_config(definitions)
    for target, source in (
        (op.Slice, op.Reconstruct),
        (op.CenterSweep, op.Reconstruct),
        (op.CorrectionPreview, op.Correct),
    ):
        props = definitions[target.__name__]["properties"]
        for name, field in definitions[source.__name__]["properties"].items():
            if name != "type" and name in props:
                props[name] = field
    return schema


def inherit_align_config(definitions: dict[str, Any]) -> None:
    """Describe the everyday alignment controls from the configuration fields they replace."""
    align = definitions["Align"]["properties"]
    for name, field in definitions["AlignConfig"]["properties"].items():
        if name in align and name != "type":
            for key in ("description", "x-unit", "x-choices"):
                if key in field:
                    align[name][key] = field[key]
            # A null setting takes the configuration's value, so a form can show it and
            # follow a `config` that changes it. Null marks a configuration default of None.
            if align[name].get("default") is None and "default" in field:
                align[name]["x-default"] = field["default"]


def describe_models(definitions: dict[str, Any]) -> None:
    """Describe the fields from their numerical constructor and unit metadata."""
    for cls in option_types():
        document = definitions[cls.__name__]
        document["description"] = plain_text(
            " ".join(NumpyDocString(inspect.getdoc(cls))["Summary"])
        )
        metadata = {f.name: f.metadata for f in fields(cls) if f.init}
        for name, field in parameters(cls).items():
            document["properties"][name].update(field)
            if "unit" in metadata[name]:
                document["properties"][name]["x-unit"] = metadata[name]["unit"]


def plain_text(text: str) -> str:
    """Remove inline reStructuredText markup from form help."""
    text = re.sub(r":[\w:-]+:`(?:([^<`]+?)\s*<[^>`]+>|~?([^`]+))`", r"\1\2", text)
    return text.replace("``", "")


def parameters(owner: Callable[..., Any]) -> dict[str, dict[str, Any]]:
    """Resolve every public argument and require its NumPy parameter documentation."""
    doc = NumpyDocString(inspect.getdoc(owner))
    help_text = {
        name.strip("* "): " ".join(x.strip() for x in param.desc)
        for section in ("Parameters", "Other Parameters")
        for param in doc[section]
        for name in param.name.split(",")
    }
    hints = get_type_hints(owner, include_extras=True)
    result = {}
    for name in inspect.signature(owner).parameters:
        if name in ("self", "cls"):
            continue
        annotation = hints[name]
        field: dict[str, Any] = {"description": plain_text(help_text[name])}
        if get_origin(annotation) is Annotated:
            annotation, unit = get_args(annotation)
            field["x-unit"] = unit
        if values := choices(annotation):
            field["x-choices"] = values
        result[name] = field
    return result


class _Options(argparse.Namespace):
    check: bool = False


def main() -> int:
    """Write generated files or verify the checked-in copies."""
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--check", action="store_true", help="Check for drift without writing.")
    check = parser.parse_args(namespace=_Options()).check

    options = render()
    drifted: list[Path] = []
    if not check:
        _ = TARGET.write_text(options, encoding="utf-8")
    elif not TARGET.is_file() or TARGET.read_bytes() != options.encode("utf-8"):
        drifted.append(TARGET)
        # The parameter description uses these types through cli.operations. Load
        # the fresh definitions so stale or missing source cannot skew that check.
        module = ModuleType("tomojax.cli.wire_options")
        sys.modules[module.__name__] = module
        exec(compile(options, str(TARGET), "exec"), vars(module))

    parameters_json = json.dumps(description(), indent=2, ensure_ascii=False) + "\n"
    if not check:
        _ = DESCRIPTION.write_text(parameters_json, encoding="utf-8")
    elif not DESCRIPTION.is_file() or DESCRIPTION.read_bytes() != parameters_json.encode("utf-8"):
        drifted.append(DESCRIPTION)

    if drifted:
        paths = ", ".join(p.relative_to(ROOT).as_posix() for p in drifted)
        print(f"Generated files are out of date: {paths}", file=sys.stderr)
        print("Regenerate with: uv run python tools/build_wire_options.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
